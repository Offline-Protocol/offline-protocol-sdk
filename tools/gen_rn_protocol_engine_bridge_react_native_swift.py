#!/usr/bin/env python3
"""Generate ProtocolEngineHostBridgeReactNative.swift and thin RN method bodies."""

from __future__ import annotations

import json
import pathlib
import re
import textwrap

REPO = pathlib.Path(__file__).resolve().parents[1]
GEN_BRIDGE = REPO / "tools/gen_protocol_engine_host_bridge.py"
MODULE = REPO / "bindings/react-native/ios/OfflineProtocolModule.swift"
OUT = REPO / "bindings/react-native/ios/ProtocolEngineHostBridgeReactNative.swift"
MANIFEST = REPO / "tools/rn_engine_bridge_error_manifest.json"

METHODS = re.findall(
    r'"(\w+)"',
    GEN_BRIDGE.read_text().split("METHODS = [", 1)[1].split("]", 1)[0],
)


def objc_method_pattern(name: str) -> re.Pattern[str]:
    return re.compile(
        rf"(?:@objc func {re.escape(name)}|@objc\({re.escape(name)}:[^)]*\)\s*\n\s*func \w+)\(([^)]*)\)"
    )


def load_manifest() -> dict[str, dict[str, str]]:
    return json.loads(MANIFEST.read_text())


def error_for(name: str, manifest: dict[str, dict[str, str]]) -> tuple[str, str]:
    entry = manifest[name]
    return entry["code"], entry["message"]


def flags_for(name: str, manifest: dict) -> str:
    """The `run` arguments after the code and message, in a fixed order.

    The same two flags as the Kotlin generator, from the same manifest entry, so
    both platforms resolve the same shape and reject with the same code.
    """
    entry = manifest[name]
    flags = ""
    if entry.get("mapProtocolErrors"):
        flags += ", mapProtocolErrors: true"
    if entry.get("parseJsonResult"):
        flags += ", parseJsonResult: true"
    return flags


def parse_objc_method(module: str, name: str) -> tuple[str, str, str]:
    m = objc_method_pattern(name).search(module)
    if not m:
        raise SystemExit(f"missing @objc func {name}")
    params = m.group(1)
    parts = [p.strip() for p in params.split(",") if p.strip()]
    if not parts:
        return "", *error_for(name, load_manifest())  # type: ignore[misc]
    last = parts[-1]
    if "rejecter" not in last and "RCTPromiseRejectBlock" not in last:
        raise SystemExit(f"{name}: missing rejecter")
    other = parts[:-1]
    # drop resolver param (second-to-last often resolver)
    if other and "resolver" in other[-1]:
        other = other[:-1]
    sig = ", ".join(other)
    return sig, *error_for(name, load_manifest())


def swift_param_names(params: str) -> list[tuple[str | None, str, str]]:
    """(external label or None for `_`, internal name, type) for each parameter."""
    if not params.strip():
        return []
    out: list[tuple[str | None, str, str]] = []
    for part in params.split(","):
        part = part.strip()
        if not part or "rejecter" in part or "resolver" in part:
            continue
        name_part, _, typ = part.partition(":")
        typ = typ.strip()
        tokens = name_part.strip().split()
        if len(tokens) == 1:
            token = tokens[0]
            if token.startswith("_"):
                out.append((None, token[1:], typ))
            else:
                out.append((token, token, typ))
        elif len(tokens) == 2 and tokens[0] == "_":
            out.append((None, tokens[1], typ))
        elif len(tokens) == 2:
            out.append((tokens[0], tokens[1], typ))
        else:
            raise SystemExit(f"unsupported Swift parameter form: {part!r}")
    return out


def param_names_call_expr(params: str) -> str:
    bits: list[str] = []
    for ext, internal, _ in swift_param_names(params):
        if ext is None:
            bits.append(internal)
        else:
            bits.append(f"{ext}: {internal}")
    return ", ".join(bits)


def build_args_expr(params: str) -> str:
    pairs = swift_param_names(params)
    if not pairs:
        return "nil"
    if len(pairs) == 1 and pairs[0][1] == "configJson":
        return "configJson"
    items = []
    for _, name, typ in pairs:
        if "NSDictionary" in typ or "[String: Any" in typ:
            items.append(f'"{name}": BridgeResults.argumentMap(from: {name} as? [String: Any])')
        elif "[NSNumber]" in typ:
            items.append(
                f'"{name}": BridgeResults.arrayFromNSNumberList({name} as? [Any]) as Any'
            )
        elif "NSArray" in typ or "[Any" in typ:
            items.append(f'"{name}": {name} as? [Any] ?? []')
        else:
            items.append(f'"{name}": {name}')
    return "[" + ", ".join(items) + "]"


def generate_swift(module: str, manifest: dict[str, dict[str, str]]) -> str:
    lines = [
        "// Generated by tools/gen_rn_protocol_engine_bridge_react_native_swift.py",
        "import Foundation",
        "import React",
        "",
        "enum ProtocolEngineHostBridgeReactNative {",
        "    /// Runs one shared-bridge method for a React Native promise.",
        "    ///",
        "    /// A string result is resolved as the string: `src/index.ts` parses the",
        "    /// ones it expects as JSON, and `JSON.parse` on an object throws.",
        "    /// `parseJsonResult` is set only where React Native has always resolved",
        "    /// an object and the shared bridge returns its JSON. `mapProtocolErrors`",
        "    /// is set only for the methods that always surfaced typed protocol codes.",
        "    /// Both come from `tools/rn_engine_bridge_error_manifest.json`.",
        "    static func run(",
        "        _ module: OfflineProtocolModule,",
        "        resolver: @escaping RCTPromiseResolveBlock,",
        "        rejecter: @escaping RCTPromiseRejectBlock,",
        "        errorCode: String,",
        "        errorMessage: String,",
        "        mapProtocolErrors: Bool = false,",
        "        parseJsonResult: Bool = false,",
        "        env: EngineBridgeEnvironment = .inert(),",
        "        _ body: (ProtocolEngineHost, EngineBridgeEnvironment) throws -> Any?",
        "    ) {",
        "        do {",
        "            let result = try body(module.engineHost, env)",
        "            let payload = parseJsonResult",
        "                ? BridgeResults.parseJsonResult(result)",
        "                : BridgeResults.toReactNative(result)",
        "            resolver(payload ?? NSNull())",
        "        } catch {",
        "            module.rejectBridgePromise(",
        "                rejecter,",
        "                error: error,",
        "                code: errorCode,",
        "                message: errorMessage,",
        "                mapProtocolErrors: mapProtocolErrors",
        "            )",
        "        }",
        "    }",
        "",
    ]
    for name in METHODS:
        params, _, _ = parse_objc_method(module, name)
        code, msg = error_for(name, manifest)
        args = build_args_expr(params)
        if params.strip():
            ext_params = params + ", resolver: @escaping RCTPromiseResolveBlock, rejecter: @escaping RCTPromiseRejectBlock"
        else:
            ext_params = "resolver: @escaping RCTPromiseResolveBlock, rejecter: @escaping RCTPromiseRejectBlock"
            call_args = "resolver: resolver, rejecter: rejecter"
        invoke = f"try ProtocolEngineHostBridge.{name}(host: host, env: env, arguments: {args})"
        flags = flags_for(name, manifest)
        lines.append(
            textwrap.indent(
                textwrap.dedent(
                    f"""
                    static func {name}(_ module: OfflineProtocolModule, {ext_params}) {{
                        run(module, resolver: resolver, rejecter: rejecter, errorCode: "{code}", errorMessage: "{msg}"{flags}) {{ host, env in
                            {invoke}
                        }}
                    }}
                    """
                ).strip(),
                "    ",
            )
        )
        lines.append("")
    lines.append("}")
    return "\n".join(lines) + "\n"


def replace_method_bodies(module: str) -> str:
    for name in METHODS:
        params, _, _ = parse_objc_method(module, name)
        names = param_names_call_expr(params)
        if names:
            call = f"ProtocolEngineHostBridgeReactNative.{name}(self, {names}, resolver: resolver, rejecter: rejecter)"
        else:
            call = f"ProtocolEngineHostBridgeReactNative.{name}(self, resolver: resolver, rejecter: rejecter)"
        module = replace_fun_body(module, name, f"        {call}")
    return module


def replace_fun_body(module: str, name: str, new_body: str) -> str:
    m = objc_method_pattern(name).search(module)
    if not m:
        raise SystemExit(f"cannot replace body for {name}")
    open_brace = module.find("{", m.end() - 1)
    if open_brace < 0:
        raise SystemExit(f"cannot replace body for {name}")
    m_end = open_brace + 1
    start = m_end
    depth = 1
    i = start
    while i < len(module) and depth:
        if module[i] == "{":
            depth += 1
        elif module[i] == "}":
            depth -= 1
        i += 1
    return module[:start] + f"\n{new_body}\n    " + module[i - 1 :]


def ensure_module_helpers(module: str) -> str:
    if "lazy var engineHost" not in module:
        insert = textwrap.dedent(
            """
                /// Shared engine host for Flutter-parity bridge delegation (ADR 0025).
                lazy var engineHost: ProtocolEngineHost = {
                    ProtocolEngineHost(onDiagnostic: { [weak self] level, message, context in
                        self?.emitDiagnostic(level: level, message: message, context: context)
                    })
                }()

                func rejectBridgePromise(
                    _ rejecter: @escaping RCTPromiseRejectBlock,
                    error: Error,
                    code: String,
                    message: String,
                    mapProtocolErrors: Bool
                ) {
                    if mapProtocolErrors {
                        rejectWithProtocolError(error, rejecter, fallbackCode: code, fallbackMessage: message)
                    } else {
                        rejecter(code, "\\(message): \\(error.localizedDescription)", error)
                    }
                }

            """
        )
        module = module.replace(
            "    private var nostrManager: NostrManager?\n",
            "    private var nostrManager: NostrManager?\n" + insert,
            1,
        )
    return module


def verify_generated_errors(generated: str, manifest: dict[str, dict[str, str]]) -> list[str]:
    problems: list[str] = []
    for name, entry in manifest.items():
        needle = f'errorCode: "{entry["code"]}", errorMessage: "{entry["message"]}"{flags_for(name, manifest)}) {{'
        if f"static func {name}(" in generated and needle not in generated:
            problems.append(f"{name}: expected `{needle}` in generated adapter")
    return problems


def main() -> None:
    import sys

    manifest = load_manifest()
    missing = [n for n in METHODS if n not in manifest]
    if missing:
        raise SystemExit(f"{MANIFEST.name} missing {missing}; run extract_rn_bridge_error_manifest.py")

    module = MODULE.read_text()
    generated = generate_swift(module, manifest)
    if "--check" in sys.argv:
        if OUT.read_text() != generated:
            print(f"{OUT.relative_to(REPO)} is stale; run {pathlib.Path(__file__).name}", file=sys.stderr)
            raise SystemExit(1)
        for name in METHODS:
            needle = f"ProtocolEngineHostBridgeReactNative.{name}(self"
            if needle not in module:
                print(
                    f"{MODULE.relative_to(REPO)} must delegate `{name}` through ProtocolEngineHostBridgeReactNative",
                    file=sys.stderr,
                )
                raise SystemExit(1)
        for problem in verify_generated_errors(generated, manifest):
            print(problem, file=sys.stderr)
            raise SystemExit(1)
        print(f"{OUT.name}: OK ({len(METHODS)} methods)")
        return
    OUT.write_text(generated)
    module = ensure_module_helpers(module)
    module = replace_method_bodies(module)
    MODULE.write_text(module)
    print(f"wrote {OUT.relative_to(REPO)} and updated {MODULE.relative_to(REPO)} ({len(METHODS)} methods)")


if __name__ == "__main__":
    main()
