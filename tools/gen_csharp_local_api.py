#!/usr/bin/env python3
"""Generate the C# local API, ProtocolConfig and its enums from the interface definition.

Everything under bindings/csharp/src/OfflineProtocol.Sdk/Generated is written here and
nowhere else. Run with --check to fail when the committed files differ from what the
current definition produces.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
TABLE_SCRIPT = REPO / "bindings/python/scripts/generate_local_api_table.py"
UDL = REPO / "crates/offline-protocol-uniffi/src/offline_protocol.udl"
SDK = REPO / "bindings/csharp/src/OfflineProtocol.Sdk"
OUT_DIR = SDK / "Generated"
HAND_WRITTEN_ENGINE = SDK / "ProtocolEngine.cs"
MANIFEST_OUT = REPO / "bindings/csharp/local_api_methods.txt"
METHODS_PER_ENGINE_PART = 80

PREFIXES = {
    "OfflineProtocol": "",
    "MeshServices": "services.",
    "DataStore": "data.",
}

# Declarations with a hand-written C# entry point (ProtocolEngine.cs), or that take a
# callback the JSON call path cannot carry. A generated wrapper for one of these would
# sit beside the hand-written method as a second overload; generate() refuses that.
SKIP_DECLARATIONS = {
    "constructor",
    "initialize_mls",
    "initialize_mls_with_file_stores",
    "enable_telemetry",
    "disable_telemetry",
    "end_telemetry_session",
    "flush_telemetry_blocking",
    "flush_telemetry",
    "start",
    "stop",
    "local_address",
    "notify_app_state",
    "poll_event",
    "set_event_callback",
    "set_ble_transport_callback",
    "set_wifi_direct_transport_callback",
    "set_reticulum_transport_callback",
    "set_nostr_transport_callback",
    "run_storage_conformance",
    "services.constructor",
    "data.constructor",
    "data.with_storage",
}

# The enums the SDK exposes, and the namespace each lives in.
ENUMS = {
    "OverflowPolicy": "OfflineProtocol.Sdk.Config",
    "MessagePriority": "OfflineProtocol.Sdk.Model",
    "ProtocolState": "OfflineProtocol.Sdk.Model",
}

# UDL scalar -> (C# type, Utf8JsonWriter call). A field of a type with no rule here is
# refused rather than guessed: teach the generator the type.
SCALARS = {
    "string": ("string", "WriteString"),
    "boolean": ("bool", "WriteBoolean"),
    "u8": ("byte", "WriteNumber"),
    "u16": ("ushort", "WriteNumber"),
    "u32": ("uint", "WriteNumber"),
    "u64": ("ulong", "WriteNumber"),
    "i32": ("int", "WriteNumber"),
    "i64": ("long", "WriteNumber"),
}


def load_table() -> tuple[dict, str]:
    spec = importlib.util.spec_from_file_location("gen_local_api_table", TABLE_SCRIPT)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {TABLE_SCRIPT}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    udl_text = UDL.read_text(encoding="utf-8")
    return mod.parse_udl(udl_text), hashlib.sha256(udl_text.encode("utf-8")).hexdigest()


def snake_to_pascal(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("_") if p)


def file_header(digest: str, usings: tuple[str, ...]) -> str:
    lines = [
        "// <auto-generated />",
        "// Generated by tools/gen_csharp_local_api.py from offline_protocol.udl",
        f"// UDL_SHA256 = {digest}",
        "// Do not edit.",
        "",
        # Generated files are outside the project's nullable context unless they opt in.
        "#nullable enable",
        "",
    ]
    lines += [f"using {u};" for u in usings]
    return "\n".join(lines) + "\n\n"


def render_method(wire: str, ret: str, receiver: str = "", static: bool = False) -> str:
    """One wrapper. A namespace function is static and always returns its result."""
    name = snake_to_pascal(wire.split(".")[-1]) + "Async"
    if static:
        signature, call = "public static Task<string>", "CallStaticAsync"
    elif ret == "void":
        signature, call = "public Task", f"{receiver}CallAsync"
    else:
        signature, call = "public Task<string>", f"{receiver}CallWithResultAsync"
    return (
        f"    {signature} {name}(string? parametersJson = null, "
        f"CancellationToken cancellationToken = default) =>\n"
        f'        {call}("{wire}", parametersJson, cancellationToken);\n'
    )


TASK_USINGS = ("System.Threading", "System.Threading.Tasks")


def wire_methods(table: dict, obj: str) -> list[tuple[str, str]]:
    prefix = PREFIXES.get(obj, "")
    out = []
    for decl, (_params, ret) in sorted(table["methods"][obj].items()):
        wire = prefix + decl
        if wire in SKIP_DECLARATIONS:
            continue
        out.append((wire, ret))
    return out


def generate_engine_parts(table: dict, digest: str) -> dict[pathlib.Path, str]:
    entries = wire_methods(table, "OfflineProtocol")
    if not entries:
        raise RuntimeError("OfflineProtocol method table is empty after SKIP_DECLARATIONS")
    outputs = {}
    for index, start in enumerate(range(0, len(entries), METHODS_PER_ENGINE_PART), 1):
        body = "\n".join(render_method(w, r) for w, r in entries[start : start + METHODS_PER_ENGINE_PART])
        outputs[OUT_DIR / f"ProtocolEngine.LocalApi.part{index:02d}.g.cs"] = (
            file_header(digest, TASK_USINGS)
            + "namespace OfflineProtocol.Sdk;\n\n"
            + "public sealed partial class ProtocolEngine\n{\n"
            + body
            + "}\n"
        )
    return outputs


def generate_statics(table: dict, digest: str) -> str:
    entries = wire_methods(table, "namespace")
    for wire, ret in entries:
        if ret == "void":
            raise RuntimeError(f"namespace function {wire} returns void; CallStaticAsync always returns a result")
    body = "\n".join(render_method(w, r, static=True) for w, r in entries)
    return (
        file_header(digest, TASK_USINGS)
        + "namespace OfflineProtocol.Sdk;\n\n"
        + "/// <summary>The interface definition's namespace functions: no engine needed.</summary>\n"
        + "public sealed partial class ProtocolEngine\n{\n"
        + body
        + "}\n"
    )


def generate_clients(table: dict, digest: str) -> str:
    blocks = []
    for class_name, obj in (("MeshServicesClient", "MeshServices"), ("DataStoreClient", "DataStore")):
        body = "\n".join(render_method(w, r, receiver="_engine.") for w, r in wire_methods(table, obj))
        blocks.append(
            f"/// <summary><c>{PREFIXES[obj]}*</c> methods of the engine.</summary>\n"
            f"public sealed class {class_name}\n{{\n"
            "    private readonly ProtocolEngine _engine;\n\n"
            f"    internal {class_name}(ProtocolEngine engine) => _engine = engine;\n\n"
            + body
            + "}\n"
        )
    return file_header(digest, TASK_USINGS) + "namespace OfflineProtocol.Sdk;\n\n" + "\n".join(blocks)


def generate_enums(table: dict, digest: str) -> str:
    blocks = []
    for name, namespace in ENUMS.items():
        variants = table["enums"].get(name)
        if not variants:
            raise RuntimeError(f"the definition has no enum {name}")
        members = "".join(f"        {v},\n" for v in variants)
        blocks.append(
            f"namespace {namespace}\n{{\n"
            f"    /// <summary><c>{name}</c> from the interface definition, spelled as on the wire.</summary>\n"
            f"    public enum {name}\n    {{\n{members}    }}\n}}\n"
        )
    return file_header(digest, ()) + "\n".join(blocks)


def config_field(name: str, udl_type: str, has_default: bool, table: dict) -> tuple[str, list[str]]:
    """(property declaration, serializer lines at statement indent) for one ProtocolConfig field."""
    prop = snake_to_pascal(name)
    base = udl_type.rstrip("?")
    optional = has_default or udl_type.endswith("?")
    value = f"config.{prop}" if not optional else prop[:1].lower() + prop[1:]

    if base in SCALARS:
        cs_type, write = SCALARS[base]
        writes = [f'writer.{write}("{name}", {value});']
    elif base in ENUMS:
        cs_type = base
        writes = [f'writer.WriteString("{name}", Wire({value}));']
    elif base in table["records"]:
        # A nested record crosses as the host's own JSON object; the engine parses it.
        cs_type = "JsonElement"
        writes = [f'writer.WritePropertyName("{name}");', f"{value}.WriteTo(writer);"]
    else:
        raise RuntimeError(f"ProtocolConfig.{name}: no C# rule for UDL type {udl_type!r}")

    if not optional:
        return f"    public required {cs_type} {prop} {{ get; init; }}\n", writes

    if cs_type == "JsonElement":
        pattern = "{ ValueKind: not (JsonValueKind.Null or JsonValueKind.Undefined) }"
    else:
        pattern = "{ }"
    lines = [f"if (config.{prop} is {pattern} {value})", "{"] + ["    " + w for w in writes] + ["}"]
    return f"    public {cs_type}? {prop} {{ get; init; }}\n", lines


def generate_config(table: dict, digest: str) -> str:
    fields = table["records"].get("ProtocolConfig")
    if not fields:
        raise RuntimeError("the definition has no ProtocolConfig dictionary")
    decls, stmts, enum_types = [], [], []
    for name, udl_type, has_default in fields:
        decl, stmt = config_field(name, udl_type, has_default, table)
        decls.append(decl)
        stmts.append(stmt)
        base = udl_type.rstrip("?")
        if base in ENUMS and base not in enum_types:
            enum_types.append(base)

    wires = []
    for enum in enum_types:
        arms = "".join(f'        {enum}.{v} => "{v}",\n' for v in table["enums"][enum])
        wires.append(
            f"    private static string Wire({enum} value) => value switch\n    {{\n"
            + arms
            + f'        _ => throw new ArgumentOutOfRangeException(nameof(value), value, "not a defined {enum} value"),\n'
            + "    };\n"
        )

    return (
        file_header(digest, ("System", "System.Buffers", "System.Text", "System.Text.Json"))
        + "namespace OfflineProtocol.Sdk.Config;\n\n"
        + "/// <summary>\n"
        + "/// <c>ProtocolConfig</c> from the interface definition (C6). A <c>required</c> property has no\n"
        + "/// default there. A nullable one does, and is left out of the JSON while it is null, so the\n"
        + "/// engine applies its own default rather than a copy of it written here.\n"
        + "/// </summary>\n"
        + "public sealed record ProtocolConfig\n{\n"
        + "\n".join(decls)
        + "}\n\n"
        + "/// <summary>Serializes a <see cref=\"ProtocolConfig\"/> as the engine's constructor reads it.</summary>\n"
        + "public static class ProtocolConfigJson\n{\n"
        + "    public static string Serialize(ProtocolConfig config)\n    {\n"
        + "        ArgumentNullException.ThrowIfNull(config);\n"
        + "        var buffer = new ArrayBufferWriter<byte>();\n"
        + "        using (var writer = new Utf8JsonWriter(buffer))\n        {\n"
        + "            writer.WriteStartObject();\n"
        + "".join(f"            {line}\n" for lines in stmts for line in lines)
        + "            writer.WriteEndObject();\n"
        + "        }\n\n"
        + "        return Encoding.UTF8.GetString(buffer.WrittenSpan);\n"
        + "    }\n\n"
        + "\n".join(wires)
        + "}\n"
    )


_PUBLIC_MEMBER = re.compile(r"^\s*public\b[^=;{(]*?\b(\w+)\s*\(", re.MULTILINE)


def hand_written_engine_members() -> set[str]:
    return set(_PUBLIC_MEMBER.findall(HAND_WRITTEN_ENGINE.read_text(encoding="utf-8")))


def refuse_shadowing(generated: dict[pathlib.Path, str]) -> None:
    """A generated engine method must never share a name with a hand-written one.

    The two differ in parameters, so the compiler accepts both and a zero-argument call
    becomes ambiguous, or binds to the generated wrapper and bypasses the hand-written
    path (as poll_event did: the wrapper went through the JSON dispatcher and lost the
    null an empty queue returns).
    """
    hand = hand_written_engine_members()
    for path, text in generated.items():
        if "partial class ProtocolEngine" not in text:
            continue
        clash = hand & set(_PUBLIC_MEMBER.findall(text))
        if clash:
            raise RuntimeError(
                f"{path.name} would shadow hand-written ProtocolEngine members {sorted(clash)}; "
                "add their declarations to SKIP_DECLARATIONS"
            )


def generate(table: dict, digest: str) -> dict[pathlib.Path, str]:
    outputs: dict[pathlib.Path, str] = generate_engine_parts(table, digest)
    outputs[OUT_DIR / "ProtocolEngine.Static.g.cs"] = generate_statics(table, digest)
    outputs[OUT_DIR / "LocalApiClients.g.cs"] = generate_clients(table, digest)
    outputs[OUT_DIR / "Enums.g.cs"] = generate_enums(table, digest)
    outputs[OUT_DIR / "ProtocolConfig.g.cs"] = generate_config(table, digest)
    refuse_shadowing(outputs)

    wires = [w for obj in ("OfflineProtocol", "namespace", "MeshServices", "DataStore") for w, _ in wire_methods(table, obj)]
    outputs[MANIFEST_OUT] = "\n".join(sorted(wires)) + "\n"
    return outputs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    table, digest = load_table()
    outputs = generate(table, digest)
    stale = sorted(p for p in OUT_DIR.glob("*.g.cs") if p not in outputs)

    if args.check:
        failed = False
        for path, content in outputs.items():
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != content:
                print(f"{path} is stale; run tools/gen_csharp_local_api.py", file=sys.stderr)
                failed = True
        for path in stale:
            print(f"{path} is not generated by this tool; run tools/gen_csharp_local_api.py", file=sys.stderr)
            failed = True
        return 1 if failed else 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(REPO)}")
    for path in stale:
        path.unlink()
        print(f"removed {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
