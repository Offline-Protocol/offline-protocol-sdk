#!/usr/bin/env python3
"""Generate C# local API wrappers from the interface definition table."""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
TABLE_SCRIPT = REPO / "bindings/python/scripts/generate_local_api_table.py"
UDL = REPO / "crates/offline-protocol-uniffi/src/offline_protocol.udl"
OUT_DIR = REPO / "bindings/csharp/src/OfflineProtocol.Sdk/Generated"
ENGINE_MONOLITH = OUT_DIR / "ProtocolEngine.LocalApi.g.cs"
CLIENTS_OUT = OUT_DIR / "LocalApiClients.g.cs"
MANIFEST_OUT = REPO / "bindings/csharp/local_api_methods.txt"
MANIFEST_COUNT_OUT = REPO / "bindings/csharp/local_api_method_count.txt"
ENGINE_PART_COUNT_OUT = REPO / "bindings/csharp/local_api_engine_part_count.txt"
METHODS_PER_ENGINE_PART = 80

LEGACY_CLIENT_FILES = (
    OUT_DIR / "MeshServicesClient.g.cs",
    OUT_DIR / "DataStoreClient.g.cs",
    OUT_DIR / "LocalApiStatic.g.cs",
)

PREFIXES = {
    "OfflineProtocol": "",
    "MeshServices": "services.",
    "DataStore": "data.",
}

# Declarations with dedicated C# entry points or covered in other PRs.
SKIP_DECLARATIONS = {
    "constructor",
    "initialize_mls",
    "initialize_mls_with_file_stores",
    "enable_telemetry",
    "disable_telemetry",
    "end_telemetry_session",
    "flush_telemetry_blocking",
    "flush_telemetry",
    "start",
    "stop",
    "local_address",
    "notify_app_state",
    "set_event_callback",
    "set_ble_transport_callback",
    "set_wifi_direct_transport_callback",
    "set_reticulum_transport_callback",
    "set_nostr_transport_callback",
    "run_storage_conformance",
    "services.constructor",
    "data.constructor",
    "data.with_storage",
}


def load_table():
    spec = importlib.util.spec_from_file_location("gen_local_api_table", TABLE_SCRIPT)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {TABLE_SCRIPT}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    udl_text = UDL.read_text(encoding="utf-8")
    return mod.parse_udl(udl_text), hashlib.sha256(udl_text.encode("utf-8")).hexdigest()


def snake_to_pascal(name: str) -> str:
    parts = name.split("_")
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def render_method(wire: str, ret: str) -> str:
    pascal = snake_to_pascal(wire.split(".")[-1])
    method = f"{pascal}Async"
    if ret == "void":
        return (
            f"    public Task {method}(string? parametersJson = null, "
            f"CancellationToken cancellationToken = default) =>\n"
            f'        CallAsync("{wire}", parametersJson, cancellationToken);'
        )
    return (
        f"    public Task<string> {method}(string? parametersJson = null, "
        f"CancellationToken cancellationToken = default) =>\n"
        f'        CallWithResultAsync("{wire}", parametersJson, cancellationToken);'
    )


def file_header(kind: str, digest: str) -> str:
    return f"""// <auto-generated />
// Generated by tools/gen_csharp_local_api.py from offline_protocol.udl
// UDL_SHA256 = {digest}
// Do not edit.

using System.Threading;
using System.Threading.Tasks;

namespace OfflineProtocol.Sdk;

"""


def engine_part_path(part_index: int) -> pathlib.Path:
    return OUT_DIR / f"ProtocolEngine.LocalApi.part{part_index:02d}.g.cs"


def legacy_engine_part_files() -> list[pathlib.Path]:
    return sorted(OUT_DIR.glob("ProtocolEngine.LocalApi.part*.g.cs"))


def generate_engine_parts(table: dict, digest: str) -> tuple[dict[pathlib.Path, str], list[str]]:
    entries: list[tuple[str, str]] = []
    manifest: list[str] = []
    for decl, (_params, ret) in sorted(table["methods"]["OfflineProtocol"].items()):
        if decl in SKIP_DECLARATIONS:
            continue
        wire = decl
        manifest.append(wire)
        entries.append((wire, ret))

    if not entries:
        raise RuntimeError("OfflineProtocol method table is empty after SKIP_DECLARATIONS")

    outputs: dict[pathlib.Path, str] = {}
    part_index = 1
    for start in range(0, len(entries), METHODS_PER_ENGINE_PART):
        chunk = entries[start : start + METHODS_PER_ENGINE_PART]
        lines = [
            file_header(f"ProtocolEngine.part{part_index:02d}", digest),
            "public sealed partial class ProtocolEngine",
            "{",
        ]
        for wire, ret in chunk:
            lines.append(render_method(wire, ret))
            lines.append("")
        lines.append("}")
        outputs[engine_part_path(part_index)] = "\n".join(lines)
        part_index += 1

    return outputs, manifest


def generate_prefixed_client(
    class_name: str,
    obj: str,
    table: dict,
    digest: str,
    engine_field: str,
) -> str:
    prefix = PREFIXES[obj]
    lines = [
        file_header(class_name, digest),
        f"public sealed class {class_name}",
        "{",
        "    private readonly ProtocolEngine _engine;",
        "",
        f"    internal {class_name}(ProtocolEngine engine) => _engine = engine;",
        "",
    ]
    manifest = []
    for decl, (_params, ret) in sorted(table["methods"][obj].items()):
        key = prefix + decl if prefix else decl
        if key in SKIP_DECLARATIONS or decl in SKIP_DECLARATIONS:
            continue
        wire = prefix + decl
        manifest.append(wire)
        pascal = snake_to_pascal(decl)
        method = f"{pascal}Async"
        if ret == "void":
            body = (
                f"    public Task {method}(string? parametersJson = null, "
                f"CancellationToken cancellationToken = default) =>\n"
                f'        _engine.CallAsync("{wire}", parametersJson, cancellationToken);'
            )
        else:
            body = (
                f"    public Task<string> {method}(string? parametersJson = null, "
                f"CancellationToken cancellationToken = default) =>\n"
                f'        _engine.CallWithResultAsync("{wire}", parametersJson, cancellationToken);'
            )
        lines.append(body)
        lines.append("")
    lines.append("}")
    return "\n".join(lines), manifest


def generate_static(table: dict, digest: str) -> str:
    lines = [
        file_header("LocalApiStatic", digest),
        "public static partial class LocalApi",
        "{",
    ]
    manifest = []
    for decl, (_params, ret) in sorted(table["methods"].get("namespace", {}).items()):
        if decl in SKIP_DECLARATIONS:
            continue
        wire = decl
        manifest.append(wire)
        pascal = snake_to_pascal(decl)
        method = f"{pascal}Async"
        if ret == "void":
            raise RuntimeError(f"namespace method {decl} returns void unexpectedly")
        lines.append(
            f"    public static Task<string> {method}(string? parametersJson = null, "
            f"CancellationToken cancellationToken = default) =>\n"
            f'        ProtocolEngine.CallStaticAsync("{wire}", parametersJson, cancellationToken);'
        )
        lines.append("")
    lines.append("}")
    return "\n".join(lines), manifest


def strip_generated_header(text: str) -> str:
    marker = "namespace OfflineProtocol.Sdk;\n\n"
    idx = text.find(marker)
    if idx == -1:
        raise RuntimeError("generated C# is missing the OfflineProtocol.Sdk namespace header")
    return text[idx + len(marker) :]


def generate_clients_bundle(
    table: dict,
    digest: str,
    services_manifest: list[str],
    data_manifest: list[str],
    static_manifest: list[str],
    services_cs: str,
    data_cs: str,
    static_cs: str,
) -> str:
    body = "\n".join(
        [
            strip_generated_header(services_cs).rstrip(),
            "",
            strip_generated_header(data_cs).rstrip(),
            "",
            strip_generated_header(static_cs).rstrip(),
            "",
        ]
    )
    return file_header("LocalApiClients", digest) + body


def remove_stale_generated_files(expected_engine_parts: set[pathlib.Path]) -> None:
    for legacy in LEGACY_CLIENT_FILES:
        if legacy.is_file():
            legacy.unlink()
            print(f"removed legacy {legacy}")
    if ENGINE_MONOLITH.is_file():
        ENGINE_MONOLITH.unlink()
        print(f"removed legacy {ENGINE_MONOLITH}")
    for path in legacy_engine_part_files():
        if path not in expected_engine_parts:
            path.unlink()
            print(f"removed stale {path}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    table, digest = load_table()
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    engine_parts, engine_manifest = generate_engine_parts(table, digest)
    services_cs, services_manifest = generate_prefixed_client(
        "MeshServicesClient", "MeshServices", table, digest, "_engine"
    )
    data_cs, data_manifest = generate_prefixed_client(
        "DataStoreClient", "DataStore", table, digest, "_engine"
    )
    static_cs, static_manifest = generate_static(table, digest)
    clients_cs = generate_clients_bundle(
        table,
        digest,
        services_manifest,
        data_manifest,
        static_manifest,
        services_cs,
        data_cs,
        static_cs,
    )

    wire_names = sorted(engine_manifest + services_manifest + data_manifest + static_manifest)
    manifest = "\n".join(wire_names) + "\n"
    method_count = f"{len(wire_names)}\n"
    engine_part_count = f"{len(engine_parts)}\n"

    outputs: dict[pathlib.Path, str] = {
        **engine_parts,
        CLIENTS_OUT: clients_cs,
        MANIFEST_OUT: manifest,
        MANIFEST_COUNT_OUT: method_count,
        ENGINE_PART_COUNT_OUT: engine_part_count,
    }
    expected_engine_parts = set(engine_parts.keys())

    if args.check:
        for path, content in outputs.items():
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != content:
                print(f"{path} is stale; run tools/gen_csharp_local_api.py", file=sys.stderr)
                return 1
        if ENGINE_MONOLITH.is_file():
            print(f"{ENGINE_MONOLITH} must not exist; run tools/gen_csharp_local_api.py", file=sys.stderr)
            return 1
        for legacy in LEGACY_CLIENT_FILES:
            if legacy.is_file():
                print(f"{legacy} must not exist; run tools/gen_csharp_local_api.py", file=sys.stderr)
                return 1
        on_disk_parts = set(legacy_engine_part_files())
        if on_disk_parts != expected_engine_parts:
            print(
                "ProtocolEngine.LocalApi.part*.g.cs on disk does not match generator output; "
                "run tools/gen_csharp_local_api.py",
                file=sys.stderr,
            )
            return 1
        return 0

    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path}")
    remove_stale_generated_files(expected_engine_parts)
    return 0


if __name__ == "__main__":
    sys.exit(main())
