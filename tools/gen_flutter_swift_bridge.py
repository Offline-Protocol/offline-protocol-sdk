#!/usr/bin/env python3
"""Generate the iOS FlutterEngineChannel.swift dispatch surface (F3).

The dispatcher is one `case` per name in method_channel_methods.txt, each a
call to the same-named static function in ProtocolEngineHostBridge.swift. The
Rust guard `flutter_method_channel_methods_match_native_plugins` reads every
`case "..."` in the output, so a method that is added to the manifest and not
regenerated fails there, and tools/gen_swift_protocol_engine_host_bridge.py
--check fails when the bridge lacks the function.

    python3 tools/gen_flutter_swift_bridge.py          # write
    python3 tools/gen_flutter_swift_bridge.py --check  # fail when stale
"""

from __future__ import annotations

import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
MANIFEST = REPO / "bindings/flutter/offline_protocol/method_channel_methods.txt"
OUT = REPO / "bindings/flutter/offline_protocol/ios/Classes/FlutterEngineChannel.swift"

HEADER = """\
// Generated by tools/gen_flutter_swift_bridge.py from method_channel_methods.txt.
// Do not edit: add the method to the manifest and to ProtocolEngineHostBridge.swift,
// then regenerate.

import Flutter
import Foundation

/// Method-channel dispatch for the Flutter plugin (F3). The Swift counterpart of
/// Android's `FlutterEngineChannel.kt`: one `case` per manifest entry, each a
/// call into `ProtocolEngineHostBridge`, which does the work against the
/// shared `ProtocolEngineHost`.
enum FlutterEngineChannel {
    /// What the bridge needs from the plugin that is not the engine: the event
    /// replay ring and the lifecycle steps that also reset the plugin's own
    /// event bookkeeping. Closures, so the bridge never names the plugin.
    struct Environment {
        let appState: () -> AppState
        let replayEvents: (Int, Int) -> [[String: Any]]
        let tearDownProtocol: () -> Void
        let createOnEngine: (String) throws -> Void
        let startOnEngine: () throws -> Void
        let stopOnEngine: () throws -> Void
    }

    /// Runs on the plugin's engine queue. A name outside the manifest answers
    /// `FlutterMethodNotImplemented`, which the plugin hands to Dart as such.
    static func dispatch(
        host: ProtocolEngineHost,
        env: Environment,
        method: String,
        arguments: Any?
    ) throws -> Any? {
        switch method {
"""

FOOTER = """\
        default:
            return FlutterMethodNotImplemented
        }
    }
}
"""


def methods() -> list[str]:
    return [ln.strip() for ln in MANIFEST.read_text().splitlines() if ln.strip()]


def render() -> str:
    lines = [HEADER]
    for m in methods():
        lines.append(f'        case "{m}":\n')
        lines.append(
            f"            return try ProtocolEngineHostBridge.{m}"
            "(host: host, env: env, arguments: arguments)\n"
        )
    lines.append(FOOTER)
    return "".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale; run tools/gen_flutter_swift_bridge.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"Wrote {OUT} ({len(methods())} methods)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
